#!/usr/bin/env python3
"""Replay GA-generated society streams through matched GA and PROV listeners.

The original fixed-stream experiment uses dialogue generated by PROV societies,
so its complete-pipeline effect is conditional on PROV-generated support.  This
cross-source audit repeats the listener intervention on eight independently
realized GA society streams from the same one-shot update task.

GA dialogue carries no structured provenance.  To separate support generation
from listener integration, the controlled task supplies an oracle version only
for unambiguous value mentions (old value = 0; updated value = 1) and for the
authoritative injection.  Ambiguous mixed utterances receive no metadata.  Both
listener conditions receive identical text and annotations; GA ignores the
metadata, while PROV can use it.  The resulting estimand is therefore
conditional on supplied task versions and is not an end-to-end claim about
natural-language provenance extraction.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from fixed_stream_integration_eval import (
    aggregate_results,
    condition_result,
    configure_transport_limits,
    load_json,
    tally,
    write_json,
)


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_RUNS_ROOT = (
    ROOT / "sim" / "runs" / "prov_batch" / "ga_r5" / "gpt-5.4-mini" / "ga"
)
DEFAULT_OUT = ROOT / "sim" / "runs" / "cross_source_integration_2026-07-23"
CURRENT_VALUE = "The repair drive is being held on Sunday at the community center."
STALE_VALUE = "The repair drive is being held on Saturday at the front porch."
CURRENT_MARKERS = ("sunday", "community center")
STALE_MARKERS = ("saturday", "front porch", "porch")


def classify_text(text: str) -> str:
    lower = text.lower()
    has_current = any(marker in lower for marker in CURRENT_MARKERS)
    has_stale = any(marker in lower for marker in STALE_MARKERS)
    if has_current and not has_stale:
        return "current"
    if has_stale and not has_current:
        return "stale"
    return "ambiguous" if (has_current and has_stale) else "irrelevant"


def annotate_event(event: dict[str, Any], *, injection: bool = False) -> str:
    if injection:
        event["prov"] = {
            "version": 1,
            "value": CURRENT_VALUE,
            "auth": True,
            "source": "ORIGIN",
            "path": ["ORIGIN"],
        }
        return "authoritative_injection"
    label = classify_text(str(event.get("text", "")))
    if label == "current":
        event["prov"] = {
            "version": 1,
            "value": CURRENT_VALUE,
            "source": str(event.get("speaker", "")),
            "annotation_basis": "controlled_task",
        }
        return "current_annotation"
    if label == "stale":
        event["prov"] = {
            "version": 0,
            "value": STALE_VALUE,
            "source": str(event.get("speaker", "")),
            "annotation_basis": "controlled_task",
        }
        return "stale_annotation"
    return f"{label}_unannotated"


def reconstruct_ga_stream(run_dir: Path) -> tuple[dict[str, Any], dict[str, Any]]:
    summary = load_json(run_dir / "sim_summary.json")
    agents = summary.get("agents", [])
    if not agents:
        raise ValueError(f"missing agents in {run_dir / 'sim_summary.json'}")
    name_to_id = {str(row["name"]): str(row["id"]) for row in agents}
    id_to_name = {str(row["id"]): str(row["name"]) for row in agents}
    events: dict[str, list[dict[str, Any]]] = {agent_id: [] for agent_id in id_to_name}
    annotation_counts = {
        "authoritative_injection": 0,
        "current_annotation": 0,
        "stale_annotation": 0,
        "ambiguous_unannotated": 0,
        "irrelevant_unannotated": 0,
    }

    round_paths = sorted(run_dir.glob("round_*.json"))
    if not round_paths:
        raise ValueError(f"no round logs in {run_dir}")
    encounter_utterances = 0
    injections = 0
    for round_path in round_paths:
        round_log = load_json(round_path)
        round_idx = int(round_log["round"])
        for encounter in round_log.get("encounters", []):
            a_id = name_to_id[str(encounter["a"])]
            b_id = name_to_id[str(encounter["b"])]
            for utterance in encounter.get("utterances", []):
                event = {
                    "round": round_idx,
                    "text": str(utterance.get("text", "")),
                    "speaker": str(utterance.get("speaker", "")),
                    "listener": str(utterance.get("listener", "")),
                }
                disposition = annotate_event(event)
                # Each participant observes the encounter transcript, matching
                # the simulator and the original fixed-stream reconstruction.
                for agent_id in (a_id, b_id):
                    events[agent_id].append(dict(event))
                    annotation_counts[disposition] += 1
                encounter_utterances += 1

        for injection in round_log.get("injected", []):
            agent_id = name_to_id[str(injection["agent"])]
            event = {
                "round": round_idx,
                "text": str(injection["text"]),
                "speaker": "world",
                "listener": str(injection["agent"]),
                "injected": True,
            }
            disposition = annotate_event(event, injection=True)
            events[agent_id].append(event)
            annotation_counts[disposition] += 1
            injections += 1

    snapshot = {
        agent_id: {
            "kind": "ga_generated_oracle_annotated_stream",
            "name": id_to_name[agent_id],
            "events": rows,
        }
        for agent_id, rows in events.items()
    }
    manifest = {
        "source_run": str(run_dir),
        "source_architecture": "ga",
        "schedule_seed": int(summary["schedule_seed"]),
        "agent_count": len(agents),
        "rounds": len(round_paths),
        "encounter_utterances": encounter_utterances,
        "event_observations": sum(len(rows) for rows in events.values()),
        "injections": injections,
        "annotation_counts": annotation_counts,
        "annotation_rule": (
            "oracle controlled-task version on unambiguous value mentions; "
            "mixed utterances unannotated"
        ),
    }
    return snapshot, manifest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs-root", type=Path, default=DEFAULT_RUNS_ROOT)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--config", type=Path, default=None)
    parser.add_argument("--model", default="gpt-5.4-mini")
    parser.add_argument("--workers", type=int, default=3)
    parser.add_argument("--timeout", type=int, default=90)
    parser.add_argument("--retries", type=int, default=1)
    parser.add_argument("--max-streams", type=int, default=8)
    parser.add_argument("--prepare-only", action="store_true")
    args = parser.parse_args()

    run_dirs = sorted(path for path in args.runs_root.glob("run_*") if path.is_dir())
    run_dirs = run_dirs[: args.max_streams]
    if not run_dirs:
        raise ValueError(f"no source runs in {args.runs_root}")
    args.out_dir.mkdir(parents=True, exist_ok=True)

    prepared: list[tuple[dict[str, Any], dict[str, Any], Path]] = []
    for run_dir in run_dirs:
        snapshot, manifest = reconstruct_ga_stream(run_dir)
        seed_dir = args.out_dir / f"seed_{manifest['schedule_seed']}"
        write_json(seed_dir / "fixed_stream.json", snapshot)
        write_json(seed_dir / "manifest.json", manifest)
        prepared.append((snapshot, manifest, seed_dir))
        print(
            f"prepared seed={manifest['schedule_seed']} "
            f"events={manifest['event_observations']} "
            f"annotations={json.dumps(manifest['annotation_counts'], sort_keys=True)}",
            flush=True,
        )

    if args.prepare_only:
        print(f"prepared {len(prepared)} GA-generated streams -> {args.out_dir}")
        return 0

    from llm import DEFAULT_CONFIG, LLM

    llm = LLM(config=args.config or DEFAULT_CONFIG, model=args.model)
    configure_transport_limits(llm, timeout=max(10, args.timeout), retries=max(0, args.retries))
    seed_results: list[dict[str, Any]] = []
    for snapshot, manifest, seed_dir in prepared:
        result_path = seed_dir / "result.json"
        if result_path.exists():
            row = load_json(result_path)
        else:
            row = {
                "schedule_seed": manifest["schedule_seed"],
                "manifest": manifest,
                "conditions": {},
            }
        for memory in ("prov", "ga"):
            interview_path = seed_dir / f"interview_{memory}.json"
            memory_path = seed_dir / f"memory_{memory}.json"
            if interview_path.exists() and memory_path.exists():
                counts = tally(load_json(interview_path))
                row["conditions"][memory] = {
                    "counts": counts,
                    "current_rate": counts["current"] / len(snapshot),
                    "stale_rate": counts["stale"] / len(snapshot),
                    "unknown_rate": counts["unknown"] / len(snapshot),
                }
                write_json(result_path, row)
                print(
                    f"reuse seed={manifest['schedule_seed']} condition={memory}",
                    flush=True,
                )
                continue
            print(f"seed={manifest['schedule_seed']} condition={memory}", flush=True)
            try:
                row["conditions"][memory] = condition_result(
                    memory,
                    snapshot,
                    llm,
                    workers=max(1, args.workers),
                    out_dir=seed_dir,
                )
            except Exception as exc:
                failure = {
                    "schedule_seed": manifest["schedule_seed"],
                    "condition": memory,
                    "error_type": type(exc).__name__,
                    "policy": "incomplete condition is not scored; rerun resumes checkpoints",
                }
                write_json(seed_dir / f"failure_{memory}.json", failure)
                print(
                    f"FAILED seed={manifest['schedule_seed']} condition={memory} "
                    f"error={type(exc).__name__}",
                    flush=True,
                )
                return 2
            write_json(result_path, row)
        seed_results.append(row)

    aggregate = aggregate_results(seed_results)
    aggregate["source_stream_model"] = "gpt-5.4-mini"
    aggregate["source_stream_architecture"] = "ga"
    aggregate["replay_model"] = args.model
    aggregate["stream_conditioning"] = (
        "realized GA dialogue streams; both memories receive identical text and "
        "oracle controlled-task versions on unambiguous value mentions"
    )
    aggregate["scope_boundary"] = (
        "conditional listener-pipeline effect with supplied task versions; "
        "not a provenance-extraction or authentication result"
    )
    aggregate["failure_policy"] = (
        "no provider failure scored as unknown; incomplete conditions resume from checkpoints"
    )
    write_json(args.out_dir / "aggregate.json", aggregate)
    print(json.dumps(aggregate, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
